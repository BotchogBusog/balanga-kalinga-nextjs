/**
 * Generates a Word-ready HTML data dictionary for Balanga Kalinga.
 *
 * Run (PowerShell):
 *   $env:DB_HOST="..."; $env:DB_PORT="..."; $env:DB_USER="..."
 *   $env:DB_PASSWORD="..."; $env:DB_NAME="..."; $env:DB_SSL="true"
 *   node scripts/generate-data-dictionary.js
 *
 * Optional: node scripts/generate-data-dictionary.js path\to\output.html
 *
 * The active-table list is deliberately explicit. A database dump may contain
 * retired tables, but only tables used by the current application belong in
 * this document.
 */
const fs = require("fs");
const path = require("path");
const mysql = require("mysql2/promise");

const ACTIVE_TABLES = [
  "users",
  "counselors",
  "appointments",
  "wellness_assessments",
  "moods",
  "ai_conversations",
  "ai_messages",
];

const TABLE_PURPOSES = {
  users: "Stores student, counselor, and administrator accounts for registration, login, role-based access, and profile management.",
  counselors: "Stores counselor professional profiles, schedules, contact details, and availability for appointment booking.",
  appointments: "Stores counseling appointment requests and their unique transaction references. It is a booking feature only and does not process payments.",
  wellness_assessments: "Stores completed 10-question wellness checks and the calculated risk feedback for each student.",
  moods: "Stores mood check-ins submitted by students from the dashboard.",
  ai_conversations: "Stores each AI wellness-companion conversation started by a student.",
  ai_messages: "Stores individual student and AI messages within an AI conversation.",
};

const FIELD_DESCRIPTIONS = {
  id: "Unique identifier for this record.",
  name: "Full name of the account holder or counselor.",
  email: "Email address used for account contact or sign-in.",
  student_id: "Unique school student identification number, when applicable.",
  password_hash: "Encrypted password value used to verify sign-in credentials.",
  role: "Account role: student, counselor, or admin.",
  course: "Student's academic course or program.",
  year_level: "Student's current academic year level.",
  school: "Student's school or institution name.",
  counselor_id: "Logical link from a counselor account to its counselor profile. It is unique; the live database does not enforce it as a physical foreign-key constraint.",
  specialization: "Counseling area or professional specialization.",
  description: "Brief description of the counselor's support area.",
  schedule: "Counselor's stated consultation schedule.",
  is_available: "Availability flag: 1 means available; 0 means unavailable.",
  phone: "Counselor contact telephone number.",
  transaction_ref: "Unique appointment reference generated by the current booking workflow, for example BK-YYYYMMDD-XXXXXXXX.",
  user_id: "References the user who owns or submitted this record.",
  requested_date: "Requested appointment calendar date.",
  requested_time: "Requested appointment time.",
  method: "Preferred counseling method, such as In-person or Phone.",
  notes: "Optional details supplied with the appointment request.",
  status: "Current appointment status: pending, approved, declined, cancelled, or completed.",
  answers: "Submitted answers for the 10-question wellness check.",
  overall_level: "Calculated wellness risk level: low, moderate, or high.",
  summary: "Supportive assessment feedback summary.",
  suggested_actions: "Suggested wellbeing actions based on the assessment.",
  mood: "Selected mood value for the student's check-in.",
  note: "Optional note recorded with the mood check-in.",
  title: "Conversation title; defaults to Talk with Kalinga AI.",
  conversation_id: "References the AI conversation containing this message.",
  content: "Text content of the AI or student message.",
  created_at: "Date and time when the record was created.",
};

const html = (value) => String(value ?? "")
  .replace(/&/g, "&amp;")
  .replace(/</g, "&lt;")
  .replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;");

function displayDefault(value, extra) {
  if (String(extra || "").toLowerCase().includes("auto_increment")) return "AUTO_INCREMENT";
  if (value === null) return "NULL";
  if (String(value).toUpperCase() === "CURRENT_TIMESTAMP") return "CURRENT_TIMESTAMP";
  if (value === "") return "''";
  return String(value);
}

function typeAndLength(columnType, dataType) {
  const varchar = /^varchar\((\d+)\)$/i.exec(columnType);
  return {
    dataType: String(dataType).toUpperCase(),
    length: varchar ? varchar[1] : "—",
  };
}

function detailAfterTable(table) {
  const cascade = new Set(["wellness_assessments", "moods", "ai_conversations", "ai_messages"]);
  if (cascade.has(table)) {
    const parent = table === "ai_messages" ? "AI conversation" : "user";
    return `When the related ${parent} is deleted, this record is also deleted (ON DELETE CASCADE).`;
  }
  if (table === "appointments") return "The system prevents a counselor from being double-booked for the same date and time while an appointment is pending or approved.";
  return "";
}

async function main() {
  const output = path.resolve(process.argv[2] || path.join(__dirname, "..", "docs", "DATA-DICTIONARY.html"));
  const config = {
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT || 3306),
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
    ssl: String(process.env.DB_SSL) === "true" ? { rejectUnauthorized: false } : undefined,
  };

  for (const key of ["host", "user", "database"]) {
    if (!config[key]) throw new Error(`Missing database setting: ${key}. Set the matching DB_* environment variable.`);
  }

  const conn = await mysql.createConnection(config);
  try {
    const [tableRows] = await conn.execute(
      `SELECT TABLE_NAME FROM information_schema.TABLES
       WHERE TABLE_SCHEMA = ? AND TABLE_NAME IN (${ACTIVE_TABLES.map(() => "?").join(",")})`,
      [config.database, ...ACTIVE_TABLES]
    );
    const existing = new Set(tableRows.map((row) => row.TABLE_NAME));
    const missing = ACTIVE_TABLES.filter((table) => !existing.has(table));
    if (missing.length) throw new Error(`Active table(s) not found: ${missing.join(", ")}`);

    const [columns] = await conn.execute(
      `SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, COLUMN_TYPE, IS_NULLABLE,
              COLUMN_DEFAULT, EXTRA, COLUMN_KEY, ORDINAL_POSITION
       FROM information_schema.COLUMNS
       WHERE TABLE_SCHEMA = ? AND TABLE_NAME IN (${ACTIVE_TABLES.map(() => "?").join(",")})
       ORDER BY FIELD(TABLE_NAME, ${ACTIVE_TABLES.map(() => "?").join(",")}), ORDINAL_POSITION`,
      [config.database, ...ACTIVE_TABLES, ...ACTIVE_TABLES]
    );
    const [foreignKeys] = await conn.execute(
      `SELECT TABLE_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME
       FROM information_schema.KEY_COLUMN_USAGE
       WHERE TABLE_SCHEMA = ? AND TABLE_NAME IN (${ACTIVE_TABLES.map(() => "?").join(",")}) AND REFERENCED_TABLE_NAME IS NOT NULL`,
      [config.database, ...ACTIVE_TABLES]
    );
    const fkMap = new Map(foreignKeys.map((row) => [
      `${row.TABLE_NAME}.${row.COLUMN_NAME}`,
      `${row.REFERENCED_TABLE_NAME}.${row.REFERENCED_COLUMN_NAME}`,
    ]));

    const byTable = new Map(ACTIVE_TABLES.map((table) => [table, []]));
    for (const column of columns) byTable.get(column.TABLE_NAME).push(column);

    const sections = ACTIVE_TABLES.map((table, index) => {
      const rows = byTable.get(table).map((column) => {
        const primary = column.COLUMN_KEY === "PRI";
        const unique = column.COLUMN_KEY === "UNI";
        const physicalFk = fkMap.get(`${table}.${column.COLUMN_NAME}`);
        const logicalCounselorFk = table === "users" && column.COLUMN_NAME === "counselor_id";
        const fk = physicalFk || logicalCounselorFk;
        const { dataType, length } = typeAndLength(column.COLUMN_TYPE, column.DATA_TYPE);
        const description = FIELD_DESCRIPTIONS[column.COLUMN_NAME] || "System data field.";
        const keyNote = physicalFk ? ` References ${physicalFk}.` : "";

        return `<tr>
          <td>${primary ? "Yes" : "No"}</td>
          <td>${logicalCounselorFk ? "Yes (logical)" : fk ? "Yes" : "No"}</td>
          <td>${unique ? "Yes" : "No"}</td>
          <td class="field">${html(column.COLUMN_NAME)}</td>
          <td>${html(dataType)}</td>
          <td>${html(length)}</td>
          <td>${column.IS_NULLABLE === "YES" ? "Yes" : "No"}</td>
          <td>${html(displayDefault(column.COLUMN_DEFAULT, column.EXTRA))}</td>
          <td class="description">${html(description + keyNote)}</td>
        </tr>`;
      }).join("\n");

      const reference = `DD-${String(index + 1).padStart(2, "0")}`;
      const extra = detailAfterTable(table);
      return `<section class="dictionary-section">
        <table class="document-header" aria-label="Data dictionary header">
          <tr><th rowspan="2">DATA DICTIONARY</th><td><strong>Reference Number:</strong> ${reference}</td></tr>
          <tr><td><strong>Version Number:</strong> 1.0</td></tr>
        </table>
        <div class="system"><strong>System Name:</strong> Balanga Kalinga: A Web-Based Student Wellness Assessment and Counseling Management System<br>
          <strong>Subject:</strong> ${html(table)}</div>
        <table class="fields" aria-label="${html(table)} data dictionary">
          <thead><tr><th>PK</th><th>FK</th><th>UK</th><th>Field Name</th><th>Data Type</th><th>Length</th><th>Nullable</th><th>Default Value</th><th>Description</th></tr></thead>
          <tbody>${rows}</tbody>
        </table>
        <p class="purpose"><strong>Table Description:</strong> ${html(TABLE_PURPOSES[table])}</p>
        ${extra ? `<p class="detail">${html(extra)}</p>` : ""}
      </section>`;
    }).join("\n");

    const document = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>Balanga Kalinga — Data Dictionary</title>
<style>
  @page { size: A4 landscape; margin: 1.2cm; }
  * { box-sizing: border-box; }
  body { font-family: Arial, sans-serif; color: #111; margin: 0; font-size: 10pt; }
  .dictionary-section { break-after: page; page-break-after: always; }
  .dictionary-section:last-child { break-after: auto; page-break-after: auto; }
  table { border-collapse: collapse; width: 100%; }
  .document-header { margin-bottom: 0; }
  .document-header th { width: 48%; background: #70ad47; color: #fff; border: 1px solid #548235; padding: 10px; text-align: left; font-size: 15pt; letter-spacing: .3px; }
  .document-header td { background: #e2f0d9; border: 1px solid #a9d18e; padding: 5px 8px; }
  .system { border: 1px solid #a9d18e; border-top: 0; padding: 7px 8px; line-height: 1.35; }
  .fields { table-layout: fixed; margin-top: 8px; }
  .fields th { background: #e2f0d9; border: 1px solid #a9d18e; padding: 5px 3px; text-align: center; vertical-align: bottom; font-size: 8.5pt; }
  .fields td { border: 1px solid #b7d7a8; padding: 5px 4px; vertical-align: top; word-wrap: break-word; }
  .fields tbody tr:nth-child(odd) { background: #eff7eb; }
  .fields th:nth-child(1), .fields td:nth-child(1) { width: 4%; text-align: center; }
  .fields th:nth-child(2), .fields td:nth-child(2) { width: 7%; text-align: center; }
  .fields th:nth-child(3), .fields td:nth-child(3) { width: 4%; text-align: center; }
  .fields th:nth-child(4), .fields td:nth-child(4) { width: 13%; }
  .fields th:nth-child(5), .fields td:nth-child(5) { width: 10%; }
  .fields th:nth-child(6), .fields td:nth-child(6) { width: 6%; text-align: center; }
  .fields th:nth-child(7), .fields td:nth-child(7) { width: 8%; text-align: center; }
  .fields th:nth-child(8), .fields td:nth-child(8) { width: 13%; }
  .fields th:nth-child(9), .fields td:nth-child(9) { width: 35%; }
  .field { font-family: "Courier New", monospace; font-weight: bold; }
  .purpose, .detail { margin: 8px 0 0; line-height: 1.35; }
  .detail { color: #333; font-style: italic; }
</style></head><body>
${sections}
</body></html>`;

    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, document, "utf8");
    console.log(`Generated ${output}`);
    console.log(`Tables: ${ACTIVE_TABLES.length} (${ACTIVE_TABLES.join(", ")})`);
  } finally {
    await conn.end();
  }
}

main().catch((error) => {
  console.error("Data dictionary generation failed:", error.message);
  process.exit(1);
});
